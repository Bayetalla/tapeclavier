import express, { Request, Response } from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json({ limit: '25mb' }));

// Initialize Google GenAI client
const apiKey = process.env.GEMINI_API_KEY || '';
const ai = new GoogleGenAI({
  apiKey,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

// 1. Text-To-Speech with gemini-3.8-flash-tts
app.post('/api/gemini/tts', async (req: Request, res: Response) => {
  try {
    const { text, voice = 'Kore', style = 'Clair, encourageant, coach de dactylographie' } = req.body;
    if (!text || typeof text !== 'string') {
      res.status(400).json({ error: 'Text parameter is required' });
      return;
    }

    if (!apiKey) {
      res.status(503).json({ error: 'GEMINI_API_KEY is not configured on the server.' });
      return;
    }

    const cleanText = text.slice(0, 400); // safety length limit
    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: cleanText,
              speechMetadata: {
                style,
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: voice },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (!base64Audio) {
      res.status(500).json({ error: 'No audio generated by Gemini TTS' });
      return;
    }

    res.json({
      audio: `data:audio/wav;base64,${base64Audio}`,
      format: 'audio/wav',
    });
  } catch (err: any) {
    console.error('Error in /api/gemini/tts:', err);
    res.status(500).json({ error: err.message || 'TTS generation failed' });
  }
});

// 2. Google Search Grounding for fresh, real-time typing articles with gemini-3.5-flash
app.post('/api/gemini/search-news', async (req: Request, res: Response) => {
  try {
    const { topic = 'technologie innovations', language = 'fr' } = req.body;

    if (!apiKey) {
      res.status(503).json({ error: 'GEMINI_API_KEY is not configured on the server.' });
      return;
    }

    const prompt = language === 'fr'
      ? `Recherche les dernières actualités et faits marquants sur le sujet "${topic}". Rédige un texte original de 80 à 130 mots, fluide et sans puces, parfait pour un exercice de dactylographie en français standard. N'inclus aucun caractère bizarre, ni markdown gras ou italique, juste du texte propre et captivant.`
      : `Search the latest news and facts about "${topic}". Write a clean, fluent typing practice passage of 80 to 130 words in standard English without markdown bolding, bullet points, or weird symbols. Make it engaging and easy to type.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.5-flash',
      contents: prompt,
      config: {
        tools: [{ googleSearch: {} }],
      },
    });

    const text = response.text?.trim() || '';
    const groundingChunks = response.candidates?.[0]?.groundingMetadata?.groundingChunks || [];

    res.json({
      text,
      topic,
      sources: groundingChunks.map((chunk: any) => ({
        title: chunk.web?.title || 'Actualité vérifiée',
        url: chunk.web?.uri || '#',
      })),
    });
  } catch (err: any) {
    console.error('Error in /api/gemini/search-news:', err);
    res.status(500).json({ error: err.message || 'Search grounding failed' });
  }
});

// 3. Image OCR & Document Scanner with gemini-3.1-pro-preview
app.post('/api/gemini/analyze-image', async (req: Request, res: Response) => {
  try {
    const { imageBase64, mimeType = 'image/jpeg' } = req.body;
    if (!imageBase64) {
      res.status(400).json({ error: 'imageBase64 parameter is required' });
      return;
    }

    if (!apiKey) {
      res.status(503).json({ error: 'GEMINI_API_KEY is not configured on the server.' });
      return;
    }

    const cleanBase64 = imageBase64.replace(/^data:[^;]+;base64,/, '');

    const response = await ai.models.generateContent({
      model: 'gemini-3.1-pro-preview',
      contents: {
        parts: [
          {
            inlineData: {
              mimeType,
              data: cleanBase64,
            },
          },
          {
            text: 'Analyse cette image (document, note manuscrite, page de livre ou code source) et transcris fidèlement son contenu textuel pour en faire un exercice dactylographique propre. Nettoie les retours à la ligne parasites pour obtenir un paragraphe fluide ou un fragment de code cohérent. Renvoie uniquement le texte à taper, sans commentaires.',
          },
        ],
      },
    });

    const transcribedText = response.text?.trim() || '';
    res.json({ text: transcribedText });
  } catch (err: any) {
    console.error('Error in /api/gemini/analyze-image:', err);
    res.status(500).json({ error: err.message || 'Image analysis failed' });
  }
});

// 4. AI Coach personalized recommendations
app.post('/api/gemini/coach', async (req: Request, res: Response) => {
  try {
    const { wpm, accuracy, weakKeys = [], fingerStats = {}, history = [] } = req.body;

    if (!apiKey) {
      // Fallback local coach recommendation if API key not available
      res.json({
        diagnosis: `Vitesse actuelle : ${wpm} WPM avec ${accuracy}% de précision.`,
        actionPlan: weakKeys.length > 0
          ? `Concentre-toi sur les touches difficiles : ${weakKeys.slice(0, 3).join(', ')}.`
          : 'Poursuis le parcours progressif pour consolider ta vitesse.',
        drills: weakKeys.length > 0 ? weakKeys.slice(0, 4) : ['f', 'j', 'd', 'k'],
      });
      return;
    }

    const prompt = `Agis comme le meilleur coach expert en apprentissage moteur et dactylographie.
Données de l'utilisateur :
- Vitesse : ${wpm} WPM
- Précision : ${accuracy}%
- Touches avec le plus d'erreurs : ${JSON.stringify(weakKeys)}
- Statistiques des doigts : ${JSON.stringify(fingerStats)}
- Historique récent : ${JSON.stringify(history.slice(-3))}

Génère en JSON :
1. "diagnosis" : Analyse bienveillante et percutante en 2 phrases (rythme, précision, fatigue potentielle).
2. "actionPlan" : Plan d'entraînement concret pour aujourd'hui (durée et objectif).
3. "recommendedDrillKeys" : Liste de 3 à 5 caractères spécifiques à cibler.
4. "customExerciseText" : Un texte d'exercice de 25-35 mots contenant spécifiquement ces touches cibles avec des mots réels.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        responseMimeType: 'application/json',
      },
    });

    try {
      const data = JSON.parse(response.text || '{}');
      res.json(data);
    } catch {
      res.json({
        diagnosis: `Bon rythme à ${wpm} WPM. Garde une régularité maximale.`,
        actionPlan: 'Fais 5 minutes de répétition sur les touches faibles.',
        recommendedDrillKeys: weakKeys.slice(0, 3),
        customExerciseText: 'La pratique régulière transforme la mémoire musculaire en réflexe instantané.',
      });
    }
  } catch (err: any) {
    console.error('Error in /api/gemini/coach:', err);
    res.status(500).json({ error: err.message || 'Coach analysis failed' });
  }
});

// Setup Vite in development or static serve in production
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const { createServer } = await import('vite');
    const vite = await createServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req: Request, res: Response) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`DactyloPro server running on http://0.0.0.0:${PORT}`);
  });
}

startServer();
